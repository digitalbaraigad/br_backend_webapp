-- Apply manually when Hibernate ddl-auto=update is disabled. No Flyway dependency is present.
CREATE TABLE IF NOT EXISTS trail_routes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    revision BIGINT,
    draft_json TEXT NOT NULL,
    published_json TEXT,
    package_version INTEGER NOT NULL DEFAULT 0,
    published BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE IF NOT EXISTS trek_histories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_email VARCHAR(255) NOT NULL,
    client_id VARCHAR(36) NOT NULL,
    payload TEXT NOT NULL,
    CONSTRAINT trek_owner_client_unique UNIQUE (owner_email, client_id)
);
